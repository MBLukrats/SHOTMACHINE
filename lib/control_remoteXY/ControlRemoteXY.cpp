static bool convertirRGB(const char* texto, uint32_t &resultado) {
    if (texto == nullptr) return false;

    String cadena = texto;
    cadena.trim();

    int coma1 = cadena.indexOf(',');
    int coma2 = cadena.indexOf(',', coma1 + 1);

    if (coma1 < 0 || coma2 < 0) return false;

    String sr = cadena.substring(0, coma1);
    String sg = cadena.substring(coma1 + 1, coma2);
    String sb = cadena.substring(coma2 + 1);

    sr.trim();
    sg.trim();
    sb.trim();

    if (sr.length() == 0 || sg.length() == 0 ||
        sb.length() == 0) {
        return false;
    }

    for (int i = 0; i < sr.length(); i++)
        if (!isDigit(sr[i])) return false;

    for (int i = 0; i < sg.length(); i++)
        if (!isDigit(sg[i])) return false;

    for (int i = 0; i < sb.length(); i++)
        if (!isDigit(sb[i])) return false;

    int r = sr.toInt();
    int g = sg.toInt();
    int b = sb.toInt();

    if (r > 255 || g > 255 || b > 255) return false;

    resultado = ((uint32_t)r << 16) |
                ((uint32_t)g << 8) |
                (uint32_t)b;

    return true;
}

bool obtenerColorPrincipalRGB(uint32_t &color) {
    return convertirRGB(RemoteXY.colorPrincipal, color);
}

bool obtenerColorFondoRGB(uint32_t &color) {
    return convertirRGB(RemoteXY.colorFondo, color);
}


static bool controlesInicializados = false;

static uint8_t ultimoEfecto = 0;
static String ultimoPrincipal = "";
static String ultimoFondo = "";

bool leerCambiosRemoteXY(
    int &efecto,
    bool &cambioEfecto,
    uint32_t &principal,
    bool &cambioPrincipal,
    uint32_t &fondo,
    bool &cambioFondo
) {
    cambioEfecto = false;
    cambioPrincipal = false;
    cambioFondo = false;

    if (!remoteXYConectado()) {
        controlesInicializados = false;
        return false;
    }

    String textoPrincipal = obtenerColorPrincipal();
    String textoFondo = obtenerColorFondo();
    uint8_t nuevoEfecto = obtenerEfectoRemoteXY();

    // Primera lectura al conectar
    if (!controlesInicializados) {
        controlesInicializados = true;

        ultimoEfecto = nuevoEfecto;
        ultimoPrincipal = textoPrincipal;
        ultimoFondo = textoFondo;

        efecto = nuevoEfecto;
        cambioEfecto = true;

        cambioPrincipal =
            convertirRGB(textoPrincipal.c_str(), principal);

        cambioFondo =
            convertirRGB(textoFondo.c_str(), fondo);

        return true;
    }

    // Selector de efectos
    if (nuevoEfecto != ultimoEfecto) {
        ultimoEfecto = nuevoEfecto;
        efecto = nuevoEfecto;
        cambioEfecto = true;
    }

    // Color principal
    if (textoPrincipal != ultimoPrincipal) {
        ultimoPrincipal = textoPrincipal;

        cambioPrincipal =
            convertirRGB(textoPrincipal.c_str(), principal);
    }

    // Color de fondo
    if (textoFondo != ultimoFondo) {
        ultimoFondo = textoFondo;

        cambioFondo =
            convertirRGB(textoFondo.c_str(), fondo);
    }

    return cambioEfecto || cambioPrincipal || cambioFondo;
}
